import os


def test_gladius_task_force_stratagems_are_implemented():
    import scripts.generate_ability_support_matrix as gsm

    stratagems = gsm._read_json(os.path.join(gsm.WAHA_DIR, "Stratagems.json"))
    expected = {
        "000008352005": "chosen devastator, tactical, or assault doctrine override",
        "000008352004": "gains [lance] on melee weapons",
        "000008352003": "fights on death after the attacking unit finishes its attacks",
        "000008352007": "reactive normal move up to d6",
        "000008352006": "gains [ignores cover] on ranged weapons",
    }

    for stratagem_id, note_anchor in expected.items():
        row = next(
            item
            for item in stratagems
            if str(item.get("id", "") or "").strip() == str(stratagem_id)
        )
        status, notes, _ = gsm._stratagem_support(
            str(row.get("name", "") or ""),
            str(row.get("description", "") or ""),
            detachment_name=str(row.get("detachment", "") or ""),
            stratagem_id=str(stratagem_id),
        )
        assert status == "Implemented"
        assert str(note_anchor).lower() in str(notes or "").lower()
